CREATE TABLE organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    type VARCHAR(50) NOT NULL CHECK (type IN ('HEALTH_CENTER', 'BRANCH', 'ADMIN_CENTER', 'COUNCIL', 'WELFARE_CENTER'))
);

CREATE TABLE dongs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    gu VARCHAR(100),
    elderly_rate DECIMAL(5,2),
    recipient_rate DECIMAL(5,2),
    single_household_rate DECIMAL(5,2),
    indicators_base_date DATE,
    CHECK (elderly_rate BETWEEN 0 AND 100),
    CHECK (recipient_rate BETWEEN 0 AND 100),
    CHECK (single_household_rate BETWEEN 0 AND 100)
);

CREATE TABLE dong_indicator_metadata (
    dong_id BIGINT NOT NULL REFERENCES dongs(id),
    indicator_key VARCHAR(100) NOT NULL,
    source VARCHAR(500),
    base_date DATE,
    denominator VARCHAR(500),
    PRIMARY KEY (dong_id, indicator_key)
);

CREATE TABLE organization_dongs (
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    dong_id BIGINT NOT NULL REFERENCES dongs(id),
    PRIMARY KEY (organization_id, dong_id)
);

CREATE TABLE places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    dong_id BIGINT NOT NULL REFERENCES dongs(id),
    address VARCHAR(500) NOT NULL,
    latitude DECIMAL(10,7) NOT NULL,
    longitude DECIMAL(10,7) NOT NULL,
    nearest_clinic_km DECIMAL(10,3),
    clinic_distance_source VARCHAR(500),
    clinic_distance_base_date DATE,
    CHECK (latitude BETWEEN -90 AND 90),
    CHECK (longitude BETWEEN -180 AND 180),
    CHECK (nearest_clinic_km >= 0)
);
CREATE INDEX idx_places_dong ON places(dong_id);

CREATE TABLE test_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    service_code VARCHAR(30) NOT NULL
);

CREATE TABLE test_type_organizations (
    test_type_id BIGINT NOT NULL REFERENCES test_types(id),
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    PRIMARY KEY (test_type_id, organization_id)
);

CREATE TABLE visit_cycles (
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    service_code VARCHAR(30) NOT NULL,
    cycle_days INTEGER CHECK (cycle_days > 0),
    PRIMARY KEY (organization_id, service_code)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('STAFF', 'ORG_MANAGER', 'ADMIN')),
    organization_id BIGINT NOT NULL REFERENCES organizations(id)
);

CREATE TABLE auth_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_auth_tokens_expiry ON auth_tokens(expires_at);
