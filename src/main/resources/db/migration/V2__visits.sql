CREATE TABLE visits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_date DATE NOT NULL,
    place_id BIGINT NOT NULL REFERENCES places(id),
    organization_id BIGINT NOT NULL REFERENCES organizations(id),
    created_by BIGINT NOT NULL REFERENCES users(id),
    memo VARCHAR(2000) NOT NULL DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX visits_place_date ON visits(place_id, visit_date);
CREATE TABLE visit_services (
    visit_id BIGINT NOT NULL REFERENCES visits(id),
    service_code VARCHAR(1) NOT NULL CHECK(service_code IN ('A','B','C','D')),
    PRIMARY KEY(visit_id, service_code)
);
CREATE TABLE visit_tests (
    visit_id BIGINT NOT NULL REFERENCES visits(id),
    test_type_id BIGINT NOT NULL REFERENCES test_types(id),
    test_count INTEGER NOT NULL CHECK(test_count > 0),
    PRIMARY KEY(visit_id, test_type_id)
);
CREATE TABLE test_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_visit_id BIGINT NOT NULL REFERENCES visits(id),
    place_id BIGINT NOT NULL REFERENCES places(id),
    test_type_id BIGINT NOT NULL REFERENCES test_types(id),
    requested_count INTEGER NOT NULL CHECK(requested_count > 0),
    requested_date DATE NOT NULL,
    requested_by_organization_id BIGINT NOT NULL REFERENCES organizations(id),
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','PLANNED','DONE')),
    planned_organization_id BIGINT REFERENCES organizations(id),
    planned_date DATE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((planned_organization_id IS NULL AND planned_date IS NULL) OR
           (planned_organization_id IS NOT NULL AND planned_date IS NOT NULL))
);
CREATE INDEX test_requests_place_status ON test_requests(place_id, status);
CREATE TABLE request_fulfillments (
    request_id BIGINT NOT NULL REFERENCES test_requests(id),
    visit_id BIGINT NOT NULL REFERENCES visits(id),
    completed_count INTEGER NOT NULL CHECK(completed_count > 0),
    PRIMARY KEY(request_id, visit_id)
);
CREATE INDEX request_fulfillments_visit ON request_fulfillments(visit_id);
