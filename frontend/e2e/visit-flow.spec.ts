async function pointOnPath(path: Locator) {
  return path.evaluate(element => {
    const bounds = element.getBoundingClientRect()
    for (let row = 2; row <= 16; row++) for (let column = 2; column <= 16; column++) {
      const x = bounds.left + bounds.width * column / 18
      const y = bounds.top + bounds.height * row / 18
      if (document.elementFromPoint(x, y) === element) return { x, y }
    }
    throw new Error('No visible point in region: ' + element.getAttribute('aria-label'))
  })
}
async function mapRegion(page: Page, label: string) {
  const path = page.locator('svg path[role="button"]').and(page.getByRole('button', { name: label, exact: true }))
  await expect(path).toBeVisible()
  const point = await pointOnPath(path)
  await page.mouse.move(point.x, point.y)
  await expect(page.getByRole('tooltip')).toContainText(label)
  return point
}

